// Inlines the SVG files into js/scenes.js so index.html works when opened straight from disk (file:// can't fetch).
// Run after editing any SVG:  node tools/bundle-scenes.mjs
//
// The scene SVGs are edited in Inkscape, so this also:
//  - strips editor-only markup (namedview, metadata, comments, XML prolog)
//  - prefixes every id per scene (all four share ids like "sky" and "navy"; inlined
//    together, url(#sky) would otherwise resolve to whichever scene came first)
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const SCENES = { quiz: 'q', password: 'p', passphrase: 'f', sticker: 's' };

function clean(svg, prefix) {
  svg = svg
    .replace(/<\?xml[^>]*\?>/g, '')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<sodipodi:namedview[\s\S]*?(\/>|<\/sodipodi:namedview>)/g, '')
    .replace(/<metadata[\s\S]*?<\/metadata>/g, '')
    .replace(/\s(sodipodi|inkscape):[\w-]+="[^"]*"/g, (m) => (m.includes('inkscape:label') ? m : ''));
  const ids = new Set([...svg.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]));
  const p = (id) => (ids.has(id) ? `${prefix}-${id}` : id);
  return svg
    .replace(/\sid="([^"]+)"/g, (_, id) => ` id="${p(id)}"`)
    .replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${p(id)})`)
    .replace(/(xlink:href|href)="#([^"]+)"/g, (_, a, id) => `${a}="#${p(id)}"`)
    .replace(/aria-labelledby="([^"]+)"/g, (_, v) => `aria-labelledby="${v.split(/\s+/).map(p).join(' ')}"`)
    .replace(/\n\s*\n/g, '\n');
}

const out = { logo: readFileSync(new URL('assets/logo.svg', root), 'utf8') };
for (const [name, prefix] of Object.entries(SCENES)) {
  out[name] = clean(readFileSync(new URL(`assets/scenes/${name}.svg`, root), 'utf8'), prefix);
}
writeFileSync(new URL('js/scenes.js', root), `// Generated by tools/bundle-scenes.mjs — edit the SVGs in assets/, not this file.\nwindow.TS_SVG = ${JSON.stringify(out)};\n`);
console.log('wrote js/scenes.js', Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.length])));

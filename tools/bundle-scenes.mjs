// Bundles the homepage artwork in assets/ into js/home-scenes.js, so the homepage also
// works when opened straight from disk (file:// pages cannot fetch the SVG files).
//
//   node tools/bundle-scenes.mjs
//
// The artwork itself is not changed. The script only:
//  - drops editor-only data (Inkscape/Sodipodi metadata, comments, hidden reference layers),
//  - prefixes every id per scene, so four files can share one page without clashes,
//  - tags the "Title card" layer, the mascot groups and the small animated parts
//    (clouds, trees, sparks, eyes…; data-ts="…") for js/home.js.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const asset = (name) => readFileSync(join(root, 'assets', name), 'utf8');

const SCENES = [
  { key: 'quiz', file: 'SpotScam - new.svg', prefix: 'q-', mascot: ['layer7'] },
  { key: 'password', file: 'PassworChecker - new.svg', prefix: 'p-', mascot: ['g72'] },
  { key: 'passphrase', file: 'Passphrase - new.svg', prefix: 'f-', mascot: ['vector-199', 'vector-254'] },
  { key: 'sticker', file: 'Sticker studio - new.svg', prefix: 's-', mascot: ['vector-375'] },
];

// layer name → data-ts tag for the idle animations in js/home.js
const LIFE = [
  [/^(cloud|cloud right|soft cream cloud)$/, 'cloud'],
  [/^(tree crown|tree bush)$/, 'sway'],
  [/^spark$/, 'spark'],
  [/^(eye|left eye|right eye)$/, 'eye'],
  [/^pwDot\d$/, 'pw-dot'],
  [/^strengthStatus\d$/, 'meter'],
  [/^alert avatar$/, 'alert'],
];

// index just past the element that starts at `start`, counting nested tags of the same name
function elementEnd(svg, start) {
  const name = /^<([\w:-]+)/.exec(svg.slice(start))[1];
  const open = svg.indexOf('>', start);
  if (svg[open - 1] === '/') return open + 1;
  const re = new RegExp(`<(/?)${name}\\b[^>]*?(/?)>`, 'g');
  re.lastIndex = open + 1;
  let depth = 1, m;
  while ((m = re.exec(svg))) {
    if (m[1]) depth--; else if (!m[2]) depth++;
    if (!depth) return re.lastIndex;
  }
  throw new Error(`unclosed <${name}>`);
}
const startOf = (svg, attr) => svg.lastIndexOf('<', svg.indexOf(attr));

function clean(svg, s) {
  svg = svg.replace(/<\?xml[^>]*>\s*/, '').replace(/<!--[\s\S]*?-->/g, '');
  // hidden layers are editor references only (the sticker file carries a 4 MB tracing image)
  let at;
  while ((at = svg.search(/<g\b[^>]*inkscape:groupmode="layer"[^>]*style="display:none"/)) !== -1) {
    svg = svg.slice(0, at) + svg.slice(elementEnd(svg, at));
  }
  at = svg.indexOf('<sodipodi:namedview');
  if (at !== -1) svg = svg.slice(0, at) + svg.slice(elementEnd(svg, at));

  // tags for home.js, added before the editor attributes they are found by are stripped
  const card = /<g\b[^>]*inkscape:label="Title card"/.exec(svg);
  if (!card) throw new Error(`${s.file}: no "Title card" layer`);
  svg = svg.slice(0, card.index) + '<g data-ts="title-card"' + svg.slice(card.index + 2);
  s.mascot.forEach((id) => {
    const i = startOf(svg, ` id="${id}"`);
    if (i < 0 || !svg.startsWith('<g', i)) throw new Error(`${s.file}: no mascot group #${id}`);
    svg = svg.slice(0, i) + '<g data-ts="mascot"' + svg.slice(i + 2);
  });
  // the small things js/home.js brings to life, found by their layer names
  svg = svg.replace(/<([\w:-]+)\b([^>]*?)\sinkscape:label="([^"]+)"/g, (tag, name, attrs, label) => {
    const kind = LIFE.find(([re]) => re.test(label));
    return kind && !attrs.includes('data-ts=') ? `<${name} data-ts="${kind[1]}"${attrs} inkscape:label="${label}"` : tag;
  });

  svg = svg
    .replace(/<inkscape:path-effect\b[^>]*\/>/g, '')
    .replace(/\s(?:inkscape|sodipodi):[\w-]+="[^"]*"/g, '')
    .replace(/-inkscape-font-specification:[^;"]*;?/g, '')
    .replace(/\s+xmlns:(?:inkscape|sodipodi|svg)="[^"]*"/g, '');

  // one prefix per scene; references are rewritten through the same map
  const ids = new Set([...svg.matchAll(/\sid="([^"]+)"/g)].map((m) => m[1]));
  const ref = (id) => (ids.has(id) ? s.prefix + id : id);
  svg = svg
    .replace(/\sid="([^"]+)"/g, (_, id) => ` id="${s.prefix}${id}"`)
    .replace(/url\(#([^)]+)\)/g, (_, id) => `url(#${ref(id)})`)
    .replace(/((?:xlink:)?href)="#([^"]+)"/g, (_, a, id) => `${a}="#${ref(id)}"`);

  // the root keeps its size for layout, the page sets the viewBox
  svg = svg.replace(/<svg\b[^>]*>/, (tag) => tag.replace(/\s(?:id|version|xml:space)="[^"]*"/g, ''));
  return svg.replace(/>\s+</g, '><').replace(/\s{2,}/g, ' ').trim();
}

const out = { logo: asset('thinksecure-logo.svg').trim() };
SCENES.forEach((s) => { out[s.key] = clean(asset(s.file), s); });

writeFileSync(join(root, 'js', 'home-scenes.js'),
  `// Generated by tools/bundle-scenes.mjs — edit the SVGs in assets/, not this file.\nwindow.TS_SVG = ${JSON.stringify(out)};\n`);
console.log(Object.entries(out).map(([k, v]) => `${k} ${(v.length / 1024).toFixed(0)} KB`).join(', '));
